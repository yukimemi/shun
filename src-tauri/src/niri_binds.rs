fn kdl_string(value: &str) -> String {
    let mut out = String::from("\"");
    for c in value.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if c.is_control() => {
                write!(out, "\\u{{{:x}}}", c as u32).unwrap();
            }
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn render(cfg: &config::Config, exe: &str) -> Result<String, String> {
    let plan = plan_hotkey_registrations(cfg);
    for warning in &plan.warnings {
        log::warn!("niri binds: {warning}");
    }
    let exe = kdl_string(exe);
    let mut out = format!(
        "// Generated by shun (niri = true). Do not edit.\nbinds {{\n    {} repeat=false {{ spawn {exe} \"toggle\"; }}\n",
        chord(&plan.launch)?
    );
    for app in plan.apps {
        let entry = &cfg.apps[app.entry_index];
        let raw = entry.hotkey.as_deref().unwrap().trim();
        let chord = match chord(&app.shortcut) {
            Ok(chord) => chord,
            Err(error) => {
                log::warn!(
                    "niri binds: apps[{}] {:?} hotkey {raw:?}: {error}, skipping",
                    app.entry_index,
                    entry.name
                );
                continue;
            }
        };
        writeln!(
            out,
            "    {} repeat=false {{ spawn {exe} \"hotkey\" {}; }}",
            chord,
            kdl_string(raw)
        )
        .unwrap();
    }
    out.push_str("}\n");
    Ok(out)
}

fn include_index(doc: &kdl::KdlDocument, binds: &Path) -> Result<usize, String> {
    let mut matches = doc.nodes().iter().enumerate().filter_map(|(index, node)| {
        if node.name().value() != "include" {
            return None;
        }
        let value = node.get(0)?.value().as_string()?;
        let included = Path::new(value);
        let relative = included
            .components()
            .filter(|c| *c != std::path::Component::CurDir)
            .eq(Path::new(BINDS_FILE).components());
        (relative || included == binds).then_some(index)
    });
    let index = matches
        .next()
        .ok_or("add include \"shun-binds.kdl\" to niri config before enabling niri sync")?;
    if matches.next().is_some() {
        return Err("shun-binds.kdl must be included exactly once".into());
    }
    Ok(index)
}

fn read_optional(path: &Path) -> Result<Option<Vec<u8>>, String> {
    match std::fs::read(path) {
        Ok(bytes) => Ok(Some(bytes)),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => Ok(None),
        Err(e) => Err(format!("read {}: {e}", path.display())),
    }
}

fn resolved_output(path: &Path) -> Result<PathBuf, String> {
    match std::fs::canonicalize(path) {
        Ok(target) => Ok(target),
        Err(e) if e.kind() == std::io::ErrorKind::NotFound => {
            if std::fs::symlink_metadata(path).is_ok() {
                return Err("shun-binds.kdl is a dangling symlink".into());
            }
            let parent = path
                .parent()
                .filter(|p| !p.as_os_str().is_empty())
                .unwrap_or(Path::new("."));
            Ok(std::fs::canonicalize(parent)
                .map_err(|e| e.to_string())?
                .join(BINDS_FILE))
        }
        Err(e) => Err(format!("resolve {}: {e}", path.display())),
    }
}

fn validate(path: &Path) -> Result<(), String> {
    let out = Command::new("niri")
        .arg("validate")
        .arg("-c")
        .arg(path)
        .output()
        .map_err(|e| format!("niri validate: {e}"))?;
    if out.status.success() {
        Ok(())
    } else {
        Err(format!(
            "niri rejected generated binds: {}",
            String::from_utf8_lossy(&out.stderr).trim()
        ))
    }
}

/// Validate a temporary main-config copy whose include points at staged binds.
/// Neither live file changes until validation succeeds; the main config is never written.
fn sync_at(
    path: &Path,
    body: &str,
    validate: impl FnOnce(&Path) -> Result<(), String>,
) -> Result<bool, String> {
    let config_target = std::fs::canonicalize(path).map_err(|e| e.to_string())?;
    let original_config = std::fs::read_to_string(path).map_err(|e| e.to_string())?;
    let mut doc: kdl::KdlDocument = original_config
        .parse()
        .map_err(|e| format!("parse niri config: {e}"))?;
    let binds = path.with_file_name(BINDS_FILE);
    let index = include_index(&doc, &binds)?;
    let target = resolved_output(&binds)?;
    if target == config_target {
        return Err("shun-binds.kdl must not resolve to niri's main config".into());
    }
    let original_binds = read_optional(&binds)?;
    if original_binds.as_deref() == Some(body.as_bytes()) {
        return Ok(false);
    }
    let parent = path
        .parent()
        .filter(|p| !p.as_os_str().is_empty())
        .unwrap_or(Path::new("."));
    let mut staged_binds = tempfile::Builder::new()
        .prefix(".shun-binds-")
        .suffix(".kdl")
        // Atomic persist must rename within the resolved output's filesystem.
        .tempfile_in(target.parent().ok_or("binds target has no parent")?)
        .map_err(|e| format!("stage binds: {e}"))?;
    staged_binds
        .write_all(body.as_bytes())
        .map_err(|e| e.to_string())?;
    if original_binds.is_some() {
        let permissions = std::fs::metadata(&target)
            .map_err(|e| e.to_string())?
            .permissions();
        staged_binds
            .as_file()
            .set_permissions(permissions)
            .map_err(|e| e.to_string())?;
    }
    let staged_path = std::fs::canonicalize(staged_binds.path()).map_err(|e| e.to_string())?;
    let staged_path = staged_path
        .to_str()
        .ok_or("staged binds path is not UTF-8")?;
    doc.nodes_mut()[index].insert(0, kdl::KdlEntry::new(staged_path));
    // A sibling keeps every other relative include resolving against its original directory.
    let mut staged_config = tempfile::Builder::new()
        .prefix(".shun-niri-")
        .suffix(".kdl")
        .tempfile_in(parent)
        .map_err(|e| format!("stage niri config: {e}"))?;
    write!(staged_config, "{doc}").map_err(|e| e.to_string())?;
    validate(staged_config.path())?;
    if std::fs::canonicalize(path).map_err(|e| e.to_string())? != config_target
        || std::fs::read_to_string(path).map_err(|e| e.to_string())? != original_config
        || resolved_output(&binds)? != target
        || read_optional(&binds)? != original_binds
    {
        return Err("niri config or binds changed during validation; no changes written".into());
    }
    staged_binds
        .persist(&target)
        .map_err(|e| format!("replace binds: {e}"))?;
    Ok(true)
}

fn config_path() -> Option<PathBuf> {
    std::env::var_os("NIRI_CONFIG")
        .filter(|p| !p.is_empty())
        .map(PathBuf::from)
        .or_else(|| dirs_next::config_dir().map(|p| p.join("niri/config.kdl")))
}

pub fn sync() -> Result<(), String> {
    static LOCK: parking_lot::Mutex<()> = parking_lot::Mutex::new(());
    let _guard = LOCK.lock();
    // Read the latest settings after taking the lock; queued reloads must not install stale binds.
    let cfg = config::load_config().0;
    if !cfg.niri || !niri::is_active() {
        return Ok(());
    }
    let exe = desktop::exe_path().ok_or("cannot resolve shun executable")?;
    let body = render(
        &cfg,
        exe.to_str().ok_or("shun executable path is not UTF-8")?,
    )?;
    let path = config_path().ok_or("cannot resolve niri config path")?;
    if sync_at(&path, &body, validate)? {
        log::info!(
            "niri binds updated: {}",
            path.with_file_name(BINDS_FILE).display()
        );
    }
    Ok(())
}


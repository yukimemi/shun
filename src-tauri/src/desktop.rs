//! Linux desktop integration: a `.desktop` entry + icon so launchers (and app menus) list
//! shun. The AppImage ships neither.
//!
//! The entry runs `<exe> show`: shun starts hidden, so a plain start would show nothing,
//! while `show` also makes a *fresh* instance open the launcher.

use std::path::{Path, PathBuf};

const ICON: &[u8] = include_bytes!("../icons/128x128.png");
/// First comment line of an entry shun wrote. Entries without it are left alone.
const MARKER: &str = "# Generated by shun";

/// `.desktop` Exec argument quoting (Desktop Entry spec, "The Exec key").
fn exec_quote(path: &str) -> String {
    let mut out = String::from("\"");
    for c in path.chars() {
        match c {
            // Reserved in quoted Exec arguments: escape for the Exec parser, then double
            // the backslash for the desktop-file string layer.
            '"' | '`' | '$' => {
                out.push_str("\\\\");
                out.push(c);
            }
            '\\' => out.push_str("\\\\\\\\"),
            '%' => out.push_str("%%"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn render_entry(exe: &Path) -> String {
    format!(
        "[Desktop Entry]\n\
         {MARKER} (desktop_integration); delete this line to keep your own edits.\n\
         Type=Application\n\
         Name=shun\n\
         Comment=Minimal keyboard-driven launcher\n\
         Exec={} show\n\
         Icon=shun\n\
         Terminal=false\n\
         Categories=Utility;\n\
         StartupWMClass=shun\n",
        exec_quote(&exe.to_string_lossy())
    )
}

/// The AppImage file when running from one (`$APPIMAGE`), else the current executable.
/// `current_exe()` inside an AppImage points into a temporary mount, so it is never used there.
pub fn exe_path() -> Option<PathBuf> {
    std::env::var_os("APPIMAGE")
        .filter(|p| !p.is_empty())
        .map(PathBuf::from)
        .or_else(|| std::env::current_exe().ok())
}

pub fn is_appimage() -> bool {
    std::env::var_os("APPIMAGE").is_some_and(|p| !p.is_empty())
}

/// What [`install`] did.
#[derive(Debug, PartialEq, Eq)]
pub enum Installed {
    Created,
    Updated,
    UpToDate,
    /// An entry without shun's marker exists; left untouched.
    UserOwned,
}

/// Writes the entry (and icon) under `data_dir` (`~/.local/share`). Existing entries are only
/// touched if shun wrote them (marker line) and their contents are stale.
fn install_into(data_dir: &Path, exe: &Path) -> Result<Installed, String> {
    let apps = data_dir.join("applications");
    let entry = apps.join("shun.desktop");
    let wanted = render_entry(exe);
    let status = match std::fs::read_to_string(&entry) {
        Ok(cur) if cur == wanted => Installed::UpToDate,
        Ok(cur) if !cur.lines().any(|l| l.starts_with(MARKER)) => Installed::UserOwned,
        Ok(_) => Installed::Updated,
        Err(_) => Installed::Created,
    };
    if matches!(status, Installed::Created | Installed::Updated) {
        std::fs::create_dir_all(&apps).map_err(|e| format!("create {}: {e}", apps.display()))?;
        std::fs::write(&entry, wanted).map_err(|e| format!("write {}: {e}", entry.display()))?;
    }
    if status != Installed::UserOwned {
        let icon_dir = data_dir.join("icons/hicolor/128x128/apps");
        let icon = icon_dir.join("shun.png");
        if !std::fs::read(&icon).is_ok_and(|cur| cur == ICON) {
            std::fs::create_dir_all(&icon_dir)
                .map_err(|e| format!("create {}: {e}", icon_dir.display()))?;
            std::fs::write(&icon, ICON).map_err(|e| format!("write {}: {e}", icon.display()))?;
        }
    }
    Ok(status)
}

/// Installs the entry for the running executable into the user's data dir.
pub fn install() -> Result<(Installed, PathBuf), String> {
    let data = dirs_next::data_dir().ok_or("cannot resolve the user data dir")?;
    let exe = exe_path().ok_or("cannot resolve the shun executable path")?;
    let status = install_into(&data, &exe)?;
    Ok((status, data.join("applications/shun.desktop")))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn exec_quote_escapes_reserved_characters() {
        assert_eq!(exec_quote("/a b/shun"), "\"/a b/shun\"");
        assert_eq!(exec_quote("/a$b"), "\"/a\\\\$b\"");
        assert_eq!(exec_quote("/a\\b"), "\"/a\\\\\\\\b\"");
        assert_eq!(exec_quote("/100%"), "\"/100%%\"");
    }

    #[test]
    fn install_creates_updates_and_respects_user_edits() {
        let dir = tempfile::tempdir().unwrap();
        let exe = Path::new("/opt/shun.AppImage");
        assert_eq!(install_into(dir.path(), exe).unwrap(), Installed::Created);
        let entry = dir.path().join("applications/shun.desktop");
        let text = std::fs::read_to_string(&entry).unwrap();
        assert!(text.contains("Exec=\"/opt/shun.AppImage\" show\n"));
        assert!(dir
            .path()
            .join("icons/hicolor/128x128/apps/shun.png")
            .exists());

        assert_eq!(install_into(dir.path(), exe).unwrap(), Installed::UpToDate);

        // AppImage moved: shun's own entry follows it.
        let moved = Path::new("/new/shun.AppImage");
        assert_eq!(install_into(dir.path(), moved).unwrap(), Installed::Updated);
        assert!(std::fs::read_to_string(&entry)
            .unwrap()
            .contains("/new/shun.AppImage"));

        // A hand-edited entry (marker removed) is never overwritten.
        std::fs::write(&entry, "[Desktop Entry]\nName=mine\n").unwrap();
        assert_eq!(install_into(dir.path(), exe).unwrap(), Installed::UserOwned);
        assert_eq!(
            std::fs::read_to_string(&entry).unwrap(),
            "[Desktop Entry]\nName=mine\n"
        );
    }
}
